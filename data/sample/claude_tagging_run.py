def parse_tags(spec: str):
    out = []
    for tok in spec.split():
        *tag, role, s = tok.split(":")
        out.append({"tag": ":".join(tag), "role": R[role], "strength": float(s)})
    return out


def main(pool_path: str, out_path: str):
    cards = [json.loads(line) for line in open(pool_path, encoding="utf-8")]
    by_name = {c["name"]: c for c in cards}
    missing = [n for n in T if n not in by_name]
    untagged = [n for n in by_name if n not in T]
    if missing or untagged:
        sys.exit(f"name mismatch: missing={missing} untagged={untagged}")
    out = []
    for name, (q, tags, vibes) in T.items():
        out.append({
            "oracle_id": by_name[name]["oracle_id"],
            "tags": parse_tags(tags),
            "quality": q,
            "vibes": [v for v in vibes.split(",") if v],
            "notes": None,
            "dropped_hints": [],
        })
    Path(out_path).write_text(json.dumps(out, indent=1), encoding="utf-8")
    print(f"{len(out)} tagged cards -> {out_path}")


if __name__ == "__main__":
    main(*sys.argv[1:3])
